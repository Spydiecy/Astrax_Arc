// Compiles contracts/*.sol with solc-js and writes lib/contracts.ts (ABI + creation bytecode).
// Run with: npm run compile:contracts
import fs from "node:fs"
import path from "node:path"
import { createRequire } from "node:module"

const require = createRequire(import.meta.url)
const solc = require("solc")
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..")
const names = ["AstraxToken", "AstraxNFT"]

const sources = Object.fromEntries(
  names.map((n) => [`${n}.sol`, { content: fs.readFileSync(path.join(root, "contracts", `${n}.sol`), "utf8") }]),
)
const input = {
  language: "Solidity",
  sources,
  settings: {
    optimizer: { enabled: true, runs: 200 },
    evmVersion: "shanghai", // Arc targets Osaka, which includes everything up to Shanghai
    outputSelection: { "*": { "*": ["abi", "evm.bytecode.object"] } },
  },
}
const out = JSON.parse(solc.compile(JSON.stringify(input)))
const errors = (out.errors || []).filter((e) => e.severity === "error")
if (errors.length) {
  console.error(errors.map((e) => e.formattedMessage).join("\n"))
  process.exit(1)
}
for (const w of (out.errors || []).filter((e) => e.severity !== "error")) console.warn(w.formattedMessage)

let ts = `// AUTO-GENERATED by scripts/compile-contracts.mjs (solc ${solc.version()}). Do not edit by hand.
// Sources live in contracts/. Re-generate with: npm run compile:contracts
`
for (const n of names) {
  const c = out.contracts[`${n}.sol`][n]
  const upper = n.replace(/([a-z])([A-Z])/g, "$1_$2").toUpperCase()
  ts += `\nexport const ${upper}_ABI = ${JSON.stringify(c.abi, null, 2)} as const\n`
  ts += `\nexport const ${upper}_BYTECODE = "0x${c.evm.bytecode.object}" as \`0x\${string}\`\n`
}
fs.writeFileSync(path.join(root, "lib", "contracts.ts"), ts)
console.log("wrote lib/contracts.ts")
